"""Backend for the /forecast what-if tool: a production port of ``working/forecasts.ipynb``.

The notebook is the design surface and remains the source of truth for the model; this module is a
faithful port of its computation so the website can answer "what if?" questions interactively. It has
two halves:

* **A context built once** (``get_context``) from the read-only attendance database — the behavioural
  models that don't depend on the committee's choices: Level 1 sign-ups (OLS), the Level 1 weekly
  attendance curve, Level 2 / social / weekender turnout, the discounted-ticket fractions, and the
  Level 2 loyalty survival curve. Only SELECTs run, and only counts and dates are read — never PII.
* **A per-request forecast** (``predict``) that takes the committee's parameter overrides, rebuilds
  the calendar and the money ledger, and propagates the attendance uncertainty through it with the
  **unscented transform** (the sigma-point method — cheap enough for live use, unlike Monte Carlo).

The sensitive financial defaults (prices, pay rates, the opening bank balance, the fitted band fee and
membership figures) are **not** committed: they load from a key,value CSV under ``working/`` — see
``config.FORECAST_DEFAULTS_PATH``, regenerated by ``working/gen_defaults.py`` — mirroring how
``attendance/early_term_stats.csv`` supplies data the schema can't. Everything a viewer can change has a
provenance note in the UI (see the frontend's control metadata). The scenario *download* is still xlsx.
"""

