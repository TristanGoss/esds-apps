# --------------------------------------------------------------------------------------------------
# Calendar (deterministic given the forecast year and the two social-count knobs)
# --------------------------------------------------------------------------------------------------
def _nth_weekday(year: int, month: int, weekday: int, n: int) -> date:
    d = date(year, month, 1)
    return d + timedelta(days=(weekday - d.weekday()) % 7 + 7 * (n - 1))


def _last_weekday(year: int, month: int, weekday: int) -> date:
    nxt = date(year + 1, 1, 1) if month == _DECEMBER else date(year, month + 1, 1)
    d = nxt - timedelta(days=1)
    return d - timedelta(days=(d.weekday() - weekday) % 7)


def _week_monday(d: date) -> date:
    return d - timedelta(days=d.weekday())


def _thursdays_between(first: date, last: date) -> list[date]:
    out, d = [], first
    while d <= last:
        out.append(d)
        d += timedelta(days=7)
    return out


def _snap_to_weekday(d: date, weekday: int) -> date:
    diff = weekday - d.weekday()
    if diff > _SNAP_HALF_WEEK:
        diff -= 7
    if diff < -_SNAP_HALF_WEEK:
        diff += 7
    return d + timedelta(days=diff)


def _best_split(n_weeks: int) -> list[int]:
    """Most-even way to cut n consecutive weeks into 5-7 week terms; longer term first on ties."""
    opts: list[list[int]] = []

    def rec(rem, acc):
        if rem == 0:
            opts.append(list(acc))
            return
        for w in range(TERM_MIN_WEEKS, TERM_MAX_WEEKS + 1):
            if w <= rem:
                acc.append(w)
                rec(rem - w, acc)
                acc.pop()

    rec(n_weeks, [])
    if not opts:
        raise ValueError(f'no 5-7 week split covers {n_weeks} weeks')
    opts.sort(key=lambda s: (max(s) - min(s), [-x for x in s]))
    return opts[0]


def build_calendar(ay: int) -> dict:
    """Derive the six-term teaching calendar and the fixed party dates for academic year ``ay``."""
    term1_first = _nth_weekday(ay, 9, THU, 2)
    xmas = date(ay, 12, 25)
    xmas_party = _week_monday(xmas) - timedelta(days=7) + timedelta(days=THU)
    term2_last = xmas_party - timedelta(days=7)
    term3_first = _nth_weekday(ay + 1, 1, THU, 2)
    eoy_party = _last_weekday(ay + 1, 6, THU)
    final_term_last = eoy_party - timedelta(days=7)
    easter_thu = _week_monday(easter(ay + 1)) + timedelta(days=THU)

    pre_xmas = _thursdays_between(term1_first, term2_last)
    post_all = _thursdays_between(term3_first, final_term_last)
    post_xmas = [d for d in post_all if d != easter_thu]
    pre_easter = [d for d in post_xmas if d < easter_thu]
    post_easter = [d for d in post_xmas if d > easter_thu]

    terms, num = [], 1
    for region in (pre_xmas, pre_easter, post_easter):
        i = 0
        for weeks in _best_split(len(region)):
            chunk = region[i : i + weeks]
            i += weeks
            terms.append({'term': num, 'start': chunk[0], 'end': chunk[-1], 'weeks': weeks, 'thursdays': chunk})
            num += 1

    return {'ay': ay, 'terms': terms, 'xmas_party': xmas_party, 'eoy_party': eoy_party, 'first_class': term1_first}


def place_socials(cal: dict, n_tea: int, have_weekender: bool) -> list[tuple[str, date]]:
    """Evenly space the tea dances (+ optional weekender) around the two fixed parties."""
    start, xmas, eoy = cal['first_class'], cal['xmas_party'], cal['eoy_party']
    n_slots = n_tea + (1 if have_weekender else 0) + 2
    grid = [start + (eoy - start) * (i + 1) / n_slots for i in range(n_slots)]
    labels: list = [None] * n_slots
    labels[-1] = ('End-of-year party', eoy)
    xi = min(range(n_slots - 1), key=lambda i: abs((grid[i] - xmas).days))
    labels[xi] = ('Christmas party', xmas)
    free = [i for i in range(n_slots) if labels[i] is None]
    if have_weekender:
        wi = free.pop()  # latest free slot -> weekender (spring)
        labels[wi] = ('Weekender', _snap_to_weekday(grid[wi], FRI))
    for j, i in enumerate(free, 1):
        labels[i] = (f'Tea dance {j}', _snap_to_weekday(grid[i], SUN))
    return labels


def _ay_of(d) -> int:
    dt = date.fromisoformat(d) if isinstance(d, str) else d
    return dt.year if dt.month >= _ACADEMIC_YEAR_START_MONTH else dt.year - 1


def _z(confidence: float) -> float:
    """Two-sided normal critical value for a confidence level (e.g. 0.95 -> 1.96)."""
    return float(stats.norm.ppf(0.5 + confidence / 2))


# --------------------------------------------------------------------------------------------------
# Level 2 loyalty: survival families
# --------------------------------------------------------------------------------------------------
_FAMILIES = {
    'geometric': (lambda k, r: r ** (k - 1), [0.7], (1e-3, 1 - 1e-3)),
    'power': (lambda k, a: k ** (-a), [1.0], (1e-3, 10.0)),
    'weibull': (lambda k, b, c: np.exp(-(((k - 1) / b) ** c)), [3.0, 1.0], ([0.1, 0.1], [50.0, 5.0])),
}


def _survival(counts):
    ks = np.arange(1, max(counts) + 1)
    return ks, np.array([np.mean([c >= k for c in counts]) for k in ks])


def _fit_family(name, ks, s):
    f, p0, bnds = _FAMILIES[name]
    popt, _ = curve_fit(f, ks, s, p0=p0, bounds=bnds, maxfev=10000)
    r2 = 1 - np.sum((s - f(ks, *popt)) ** 2) / np.sum((s - s.mean()) ** 2)
    return popt, float(r2)


